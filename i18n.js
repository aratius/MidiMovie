  const LANGS = [
    { id: 'en', label: 'English', htmlLang: 'en' },
    { id: 'zh', label: '中文', htmlLang: 'zh-Hans' },
    { id: 'ja', label: '日本語', htmlLang: 'ja' }
  ];

  let lang = 'en';
  try {
    const saved = localStorage.getItem('midimovie.lang');
    if (saved && DICT[saved]) lang = saved;
  } catch (e) { /* storage may be unavailable */ }

  const listeners = [];

  function t(key, vars) {
    let s = (DICT[lang] && DICT[lang][key]) || DICT.en[key] || key;
    if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
    return s;
  }

  function applyStatic(root) {
    root = root || document;
    root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll('[data-i18n-title]').forEach(el => {
      const s = t(el.dataset.i18nTitle);
      el.title = s; el.setAttribute('aria-label', s);
    });
    root.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  }

  function setLang(id) {
    if (!DICT[id]) return;
    lang = id;
    try { localStorage.setItem('midimovie.lang', id); } catch (e) { /* ignore */ }
    document.documentElement.lang = LANGS.find(l => l.id === id).htmlLang;
    applyStatic();
    listeners.forEach(fn => fn(id));
  }

  window.I18N = {
    t, setLang, applyStatic, LANGS,
    get lang() { return lang; },
    onChange(fn) { listeners.push(fn); }
  };
